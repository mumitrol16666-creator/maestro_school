import test from "node:test";
import assert from "node:assert/strict";
import {randomUUID} from "node:crypto";
import {prisma} from "../../infrastructure/database/prisma.js";
import {applyRetrospectiveTopicPoints,previewRetrospectiveTopicPoints} from "./points-retrospective.service.js";
const dbtest=process.env.RUN_DB_INTEGRATION_TESTS==="1"?test:test.skip;
dbtest("retrospective rewards require the confirmed report, preserve the event date, and cannot duplicate an old-account award",async t=>{
  const suffix=randomUUID().slice(0,8),crmStudentId=`retro-${suffix}`,crmClassId=`retro-class-${suffix}`;
  const studentRole=await prisma.role.upsert({where:{slug:"student"},create:{slug:"student",name:"student"},update:{}});
  const adminRole=await prisma.role.upsert({where:{slug:"admin"},create:{slug:"admin",name:"admin"},update:{}});
  const student=await prisma.user.create({data:{login:`retro-s-${suffix}`,phone:`retro-s-${suffix}`,firstName:"Ученик",lastName:"Ретро",passwordHash:"x",roleId:studentRole.id,crmStudentId,createdAt:new Date("2026-11-01T06:00:00Z")}});
  const actor=await prisma.user.create({data:{login:`retro-a-${suffix}`,phone:`retro-a-${suffix}`,firstName:"Админ",lastName:"Ретро",passwordHash:"x",roleId:adminRole.id}});
  const direction=await prisma.direction.create({data:{title:"Ретро",slug:`retro-${suffix}`}});
  const epoch=await prisma.economicEpoch.findFirstOrThrow({where:{status:"active"}});
  const eventAt=new Date("2026-10-01T06:00:00Z");
  const topic=await prisma.learningTopic.create({data:{directionId:direction.id,crmStudentId,title:"Ритм",progressPercent:100,masteredAt:eventAt}});
  await prisma.learningTopicProgress.create({data:{topicId:topic.id,toPercent:100,source:"lesson",sourceKey:`offline-lesson:${crmClassId}:topic:${topic.id}`,occurredAt:eventAt}});
  await prisma.economicEpochParticipant.create({data:{epochId:epoch.id,studentId:student.id,sourceKey:`retro:${student.id}`,activatedAt:student.createdAt}});
  await prisma.offlineLessonProjection.create({data:{crmClassId,crmTeacherId:`retro-${suffix}`,status:"completed",lessonPayload:{},rosterPayload:[],rosterVersion:"v1"}});
  const report=await prisma.offlineLessonReport.create({data:{crmClassId,authorUserId:actor.id,status:"confirmed",currentVersion:1,confirmedVersion:1,versions:{create:{version:1,authorUserId:actor.id,payload:{learningResultsV2:{homeworkDecisions:[],topicUpdates:[{topicId:topic.id,toPercent:100,expectedPercent:99}]}},attendancePayload:[{crmStudentId,attendanceStatus:"present"}],state:"confirmed"}}}});
  t.after(async()=>{
    await prisma.auditLog.deleteMany({where:{actorId:actor.id}});
    await prisma.pointsTransaction.deleteMany({where:{studentId:{in:[student.id,actor.id]}}});
    await prisma.offlineLessonReport.delete({where:{id:report.id}});
    await prisma.offlineLessonProjection.delete({where:{crmClassId}});
    await prisma.learningTopic.delete({where:{id:topic.id}});
    await prisma.direction.delete({where:{id:direction.id}});
    await prisma.user.deleteMany({where:{id:{in:[student.id,actor.id]}}});
  });
  const input={studentId:student.id,crmStudentId,epochId:epoch.id,topicIds:[topic.id]};
  const preview=await previewRetrospectiveTopicPoints(input);
  assert.equal(preview.pending,100);
  assert.equal(await prisma.pointsTransaction.count({where:{studentId:student.id}}),0);
  await prisma.offlineLessonReport.update({where:{id:report.id},data:{status:"pending_review"}});
  await assert.rejects(previewRetrospectiveTopicPoints(input));
  await prisma.offlineLessonReport.update({where:{id:report.id},data:{status:"confirmed"}});
  const other=await prisma.pointsTransaction.create({data:{studentId:actor.id,amount:100,reason:"Other account",sourceKey:`learning-topic-mastery:${topic.id}:${actor.id}`,economicEpochId:epoch.id}});
  await assert.rejects(previewRetrospectiveTopicPoints(input));
  await prisma.pointsTransaction.delete({where:{id:other.id}});
  await assert.rejects(applyRetrospectiveTopicPoints(input,"stale",actor.id));
  assert.equal((await applyRetrospectiveTopicPoints(input,preview.fingerprint,actor.id)).awarded,100);
  assert.equal((await applyRetrospectiveTopicPoints(input,preview.fingerprint,actor.id)).awarded,0);
  const receipts=await prisma.pointsTransaction.findMany({where:{studentId:student.id}});
  assert.equal(receipts.length,1);
  assert.equal(receipts[0]!.createdAt.toISOString(),eventAt.toISOString());
});
