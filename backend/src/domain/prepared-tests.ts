function question(id: string, prompt: string, options: string[], correctIndex: number): HomeworkTestQuestion {
  const polishedDistractors = polishedDistractorsByQuestion[id];
  let distractorIndex = 0;
  const balancedOptions = options.map((option, index) => {
    if (index === correctIndex) {
      return polishedCorrectAnswerByQuestion[id] ?? conciseCorrectOptionByQuestion[id] ?? option;
    }
    const replacement = polishedDistractors?.[distractorIndex];
    distractorIndex += 1;
    return replacement ?? option;
  });
  const shift = [...id].reduce((sum, character) => sum + character.charCodeAt(0), 0) % balancedOptions.length;
  const correctText = balancedOptions[correctIndex];
  const orderedOptions = balancedOptions.map((_, index) => balancedOptions[(index + shift) % balancedOptions.length]);
  return {
    id,
    prompt,
    correctOptionId: `${id}-${orderedOptions.indexOf(correctText) + 1}`,
    options: orderedOptions.map((text, index) => ({ id: `${id}-${index + 1}`, text })),
  };
}

function template(id: string, title: string, description: string, questions: HomeworkTestQuestion[]): PreparedTestTemplate {
  return { id, title, description, questions };
}

