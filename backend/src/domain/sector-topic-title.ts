/**
 * Ключ названия темы ступени: пробелы схлопнуты, регистр русский без различий.
 * Тема открытого сектора хранит только название (линии у неё нет), поэтому по этому ключу
 * урок находит материалы темы ступени, а редактор ступеней не даёт завести два одинаковых названия.
 */
export function topicTitleKey(title: string) {
  return title.replace(/\s+/g, " ").trim().toLocaleLowerCase("ru");
}
